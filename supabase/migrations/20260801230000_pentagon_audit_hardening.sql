-- Pentagon audit hardening: the project is a single-operator workspace, so a
-- generic authenticated user must not inherit its CRM, outreach, or operations
-- data. public.is_operator() is an existing security-definer allow-list check.

begin;

do $$
declare
  target_table text;
  target_policy text;
begin
  foreach target_table in array array[
    'app_settings', 'contacts', 'messages', 'outreach', 'prospecting_runs',
    'prospects', 'sequence_enrollments', 'sequence_steps', 'sequences',
    'tone_memory', 'tracked_links'
  ] loop
    for target_policy in
      select p.policyname from pg_policies p
      where p.schemaname = 'public' and p.tablename = target_table
    loop
      execute format('drop policy if exists %I on public.%I', target_policy, target_table);
    end loop;

    execute format('revoke all on table public.%I from anon, authenticated', target_table);
    execute format('grant select, insert, update, delete on table public.%I to authenticated', target_table);
    execute format(
      'create policy %I on public.%I for all to authenticated using (public.is_operator()) with check (public.is_operator())',
      target_table || '_operator_only', target_table
    );
  end loop;
end $$;


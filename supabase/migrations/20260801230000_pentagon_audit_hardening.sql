-- Replace direct anonymous rate_events access with one atomic claim. The caller
-- supplies an HMACed IP hash, so a direct caller cannot target a real visitor's
-- bucket without the function-only AUDIT_RATE_LIMIT_SALT.
do $$
declare target_policy text;
begin
  for target_policy in
    select p.policyname from pg_policies p
    where p.schemaname = 'public' and p.tablename = 'rate_events'
  loop
    execute format('drop policy if exists %I on public.rate_events', target_policy);
  end loop;
end $$;

revoke all on table public.rate_events from anon, authenticated;

create or replace function public.claim_audit_rate(p_ip_hash text, p_limit integer default 4)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  effective_limit integer := greatest(1, least(coalesce(p_limit, 4), 4));
begin
  if p_ip_hash !~ '^[0-9a-f]{32}$' then
    return false;
  end if;

  perform pg_advisory_xact_lock(hashtext('audit-rate:' || p_ip_hash));
  delete from public.rate_events
    where ip_hash = p_ip_hash
      and created_at < now() - interval '1 hour';

  if exists (
    select 1 from public.rate_events
    where ip_hash = p_ip_hash
      and kind = 'audit'
      and created_at >= now() - interval '1 hour'
    group by ip_hash
    having count(*) >= effective_limit
  ) then
    return false;
  end if;

  insert into public.rate_events (ip_hash, kind) values (p_ip_hash, 'audit');
  return true;
end;
$$;

revoke all on function public.claim_audit_rate(text, integer) from public;
grant execute on function public.claim_audit_rate(text, integer) to anon, authenticated;

-- A tracked-link UUID is unguessable, but anonymous table SELECT still exposes
-- the table contract. Resolve only the requested row through this RPC instead.
create or replace function public.resolve_tracking_link(p_link_id uuid)
returns table (id uuid, message_id uuid, url text)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select l.id, l.message_id, l.url
  from public.tracked_links l
  where l.id = p_link_id
  limit 1;
$$;

revoke all on function public.resolve_tracking_link(uuid) from public;
grant execute on function public.resolve_tracking_link(uuid) to anon, authenticated;

commit;
